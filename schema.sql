-- Simpan transaksi, detail buku, dan pengurangan stok dalam satu transaksi PostgreSQL.
drop function if exists public.record_sale(text, text, text, jsonb);
drop function if exists public.record_sale(uuid, text, text, text, jsonb);
create or replace function public.record_sale(
    p_customer_id uuid,
    p_customer_name text,
    p_customer_phone text,
    p_payment_method text,
    p_amount_received numeric,
    p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_sale public.sales%rowtype;
    new_customer_id uuid;
    new_customer_name text;
    item jsonb;
    selected_book public.books%rowtype;
    item_quantity integer;
    sale_total numeric(12, 2) := 0;
    sale_items_json jsonb := '[]'::jsonb;
    journal_debit_account text;
begin
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'Transaksi harus memiliki minimal satu buku.' using errcode = '22023';
    end if;

    new_customer_id := p_customer_id;

    if new_customer_id is null and nullif(trim(p_customer_name), '') is not null then
        insert into public.customers (name, phone)
        values (trim(p_customer_name), nullif(trim(p_customer_phone), ''))
        returning customer_id into new_customer_id;
    end if;

    if new_customer_id is not null then
        select name into new_customer_name
        from public.customers
        where customer_id = new_customer_id;
    end if;
    new_customer_name := coalesce(nullif(trim(p_customer_name), ''), nullif(trim(new_customer_name), ''), 'Pelanggan umum');

    insert into public.sales (receipt_number, customer_id, customer_name, payment_method, total)
    values (
        'NLA-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS') || '-' || upper(substr(md5(random()::text), 1, 4)),
        new_customer_id,
        new_customer_name,
        p_payment_method,
        0
    ) returning * into new_sale;

    for item in select value from jsonb_array_elements(p_items)
    loop
        item_quantity := (item ->> 'quantity')::integer;
        if item_quantity <= 0 then
            raise exception 'Jumlah buku harus lebih dari nol.' using errcode = '22023';
        end if;

        select * into selected_book
        from public.books
        where book_id = (item ->> 'book_id')::uuid
        for update;

        if not found then
            raise exception 'Buku tidak ditemukan.' using errcode = 'P0002';
        end if;
        if selected_book.stock < item_quantity then
            raise exception 'Stok % tidak mencukupi. Tersedia: %.', selected_book.title, selected_book.stock
                using errcode = 'P0001';
        end if;

        update public.books
        set stock = stock - item_quantity, updated_at = now()
        where book_id = selected_book.book_id;


        sale_items_json := sale_items_json || jsonb_build_array(jsonb_build_object(
            'book_id', selected_book.book_id,
            'title', selected_book.title,
            'quantity', item_quantity,
            'unit_price', selected_book.price
        ));
        sale_total := sale_total + selected_book.price * item_quantity;
    end loop;

    if p_amount_received is null or p_amount_received < sale_total then
        raise exception 'Jumlah uang yang diterima tidak boleh kurang dari total pembayaran.' using errcode = '22023';
    end if;

    update public.sales set total = sale_total, amount_received = p_amount_received, items = sale_items_json
    where sale_id = new_sale.sale_id
    returning * into new_sale;

    journal_debit_account := case p_payment_method
        when 'Tunai' then 'Kas'
        when 'Debit' then 'Bank - Debit'
        when 'Transfer' then 'Bank - Transfer'
        when 'QRIS' then 'Bank - QRIS'
        else null
    end;
    if journal_debit_account is null then
        raise exception 'Metode pembayaran tidak valid.' using errcode = '22023';
    end if;

    if sale_total > 0 then
        insert into public.journal_entries (
            entry_number, entry_type, description, debit_account, credit_account,
            amount, items, source_type, source_id, entry_date
        ) values (
            'JU-' || new_sale.receipt_number,
            'sale',
            'Penjualan ' || new_sale.receipt_number,
            journal_debit_account,
            'Pendapatan Penjualan',
            sale_total,
            sale_items_json,
            'sale',
            new_sale.sale_id::text,
            new_sale.sold_at
        );
    end if;

    return to_jsonb(new_sale);
end;
$$;

-- Mutasi stok dan jurnal berpasangan disimpan dalam satu transaksi.
create or replace function public.record_stock_adjustment(
    p_adjustment_type text,
    p_supplier_name text,
    p_warehouse_location text,
    p_credit_account text,
    p_notes text,
    p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    item jsonb;
    selected_book public.books%rowtype;
    item_quantity integer;
    item_cost numeric(12, 2);
    adjustment_total numeric(12, 2) := 0;
    adjustment_items_json jsonb := '[]'::jsonb;
    new_entry public.journal_entries%rowtype;
    entry_debit_account text;
    entry_credit_account text;
    entry_description text;
begin
    if p_adjustment_type is null or p_adjustment_type not in ('restock', 'damaged', 'lost') then
        raise exception 'Jenis penyesuaian stok tidak valid.' using errcode = '22023';
    end if;
    if p_adjustment_type = 'restock' and nullif(trim(p_supplier_name), '') is null then
        raise exception 'Nama supplier wajib diisi untuk restok.' using errcode = '22023';
    end if;
    if p_adjustment_type = 'restock' and (p_credit_account is null or p_credit_account not in ('Kas', 'Utang Supplier')) then
        raise exception 'Akun pembayaran restok tidak valid.' using errcode = '22023';
    end if;
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'Pilih minimal satu buku untuk penyesuaian.' using errcode = '22023';
    end if;

    for item in select value from jsonb_array_elements(p_items)
    loop
        item_quantity := (item ->> 'quantity')::integer;
        item_cost := coalesce((item ->> 'unit_cost')::numeric, 0);
        if item_quantity <= 0 or item_cost <= 0 then
            raise exception 'Jumlah dan nilai per buku harus lebih dari nol.' using errcode = '22023';
        end if;

        select * into selected_book from public.books
        where book_id = (item ->> 'book_id')::uuid for update;
        if not found then
            raise exception 'Buku pada penyesuaian tidak ditemukan.' using errcode = 'P0002';
        end if;

        if p_adjustment_type = 'restock' then
            update public.books
            set stock = stock + item_quantity,
                warehouse_location = coalesce(nullif(trim(p_warehouse_location), ''), warehouse_location),
                updated_at = now()
            where book_id = selected_book.book_id;
        else
            if selected_book.stock < item_quantity then
                raise exception 'Stok % tidak mencukupi. Tersedia: %.', selected_book.title, selected_book.stock
                    using errcode = 'P0001';
            end if;
            update public.books
            set stock = stock - item_quantity, updated_at = now()
            where book_id = selected_book.book_id;

        end if;

        adjustment_items_json := adjustment_items_json || jsonb_build_array(jsonb_build_object(
            'book_id', selected_book.book_id,
            'title', selected_book.title,
            'quantity', item_quantity,
            'unit_cost', item_cost
        ));
        adjustment_total := adjustment_total + item_quantity * item_cost;
    end loop;

    entry_debit_account := case p_adjustment_type
        when 'restock' then 'Persediaan Buku'
        when 'damaged' then 'Kerugian Buku Rusak'
        when 'lost' then 'Kerugian Buku Hilang'
    end;
    entry_credit_account := case p_adjustment_type
        when 'restock' then p_credit_account
        else 'Persediaan Buku'
    end;
    entry_description := case p_adjustment_type
        when 'restock' then 'Pembelian persediaan dari ' || trim(p_supplier_name)
        when 'damaged' then 'Pengurangan stok buku rusak'
        when 'lost' then 'Pengurangan stok buku hilang'
    end;
    if nullif(trim(p_notes), '') is not null then
        entry_description := entry_description || ': ' || trim(p_notes);
    end if;

    insert into public.journal_entries (
        entry_number, entry_type, description, debit_account, credit_account,
        amount, items, entry_date
    ) values (
        'JU-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS') || '-' || upper(substr(md5(random()::text), 1, 4)),
        case p_adjustment_type when 'restock' then 'purchase' else p_adjustment_type end,
        entry_description,
        entry_debit_account,
        entry_credit_account,
        adjustment_total,
        adjustment_items_json,
        now()
    ) returning * into new_entry;

    if p_adjustment_type in ('damaged', 'lost') then
        for item in select value from jsonb_array_elements(adjustment_items_json)
        loop
            insert into public.book_condition_events (
                book_id, condition_type, quantity, notes, journal_entry_id, occurred_at
            ) values (
                (item ->> 'book_id')::uuid,
                p_adjustment_type,
                (item ->> 'quantity')::integer,
                nullif(trim(p_notes), ''),
                new_entry.journal_entry_id,
                now()
            );
        end loop;
    elsif p_adjustment_type = 'restock' then
        for item in select value from jsonb_array_elements(adjustment_items_json)
        loop
            insert into public.book_condition_events (
                book_id, condition_type, quantity, notes, journal_entry_id, occurred_at
            ) values (
                (item ->> 'book_id')::uuid,
                'restocked',
                (item ->> 'quantity')::integer,
                nullif(trim(p_notes), ''),
                new_entry.journal_entry_id,
                now()
            );
        end loop;
    end if;

    return to_jsonb(new_entry);
end;
$$;

create or replace function public.revise_journal_amount(
    p_journal_entry_id bigint,
    p_new_amount numeric,
    p_revision_note text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    revised_entry public.journal_entries%rowtype;
begin
    if p_new_amount is null or p_new_amount <= 0 then
        raise exception 'Nominal revisi harus lebih dari nol.' using errcode = '22023';
    end if;

    select * into revised_entry
    from public.journal_entries
    where journal_entry_id = p_journal_entry_id
    for update;
    if not found then
        raise exception 'Entri jurnal tidak ditemukan.' using errcode = 'P0002';
    end if;

    update public.journal_entries
    set original_amount = coalesce(original_amount, amount),
        amount = p_new_amount,
        revision_count = revision_count + 1,
        revision_note = nullif(trim(p_revision_note), ''),
        revised_at = now()
    where journal_entry_id = p_journal_entry_id
    returning * into revised_entry;

    return to_jsonb(revised_entry);
end;
$$;

create or replace function public.delete_journal_entry(
    p_journal_entry_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    target_entry public.journal_entries%rowtype;
    target_sale public.sales%rowtype;
    item jsonb;
    target_book public.books%rowtype;
    item_quantity integer;
begin
    select * into target_entry
    from public.journal_entries
    where journal_entry_id = p_journal_entry_id
    for update;

    if not found then
        raise exception 'Entri jurnal tidak ditemukan.' using errcode = 'P0002';
    end if;

    if target_entry.entry_type = 'sale' then
        if nullif(target_entry.source_id, '') is not null then
            begin
                select * into target_sale
                from public.sales
                where sale_id = target_entry.source_id::bigint;
            exception when invalid_text_representation then
                target_sale := null;
            end;

            if target_sale.sale_id is not null then
                for item in select value from jsonb_array_elements(coalesce(target_sale.items, '[]'::jsonb))
                loop
                    item_quantity := greatest((item ->> 'quantity')::integer, 0);
                    if item_quantity > 0 then
                        update public.books
                        set stock = stock + item_quantity, updated_at = now()
                        where book_id = (item ->> 'book_id')::uuid;
                    end if;
                end loop;
                delete from public.sales where sale_id = target_sale.sale_id;
            end if;
        elsif jsonb_typeof(target_entry.items) = 'array' then
            for item in select value from jsonb_array_elements(target_entry.items)
            loop
                item_quantity := greatest((item ->> 'quantity')::integer, 0);
                if item_quantity > 0 then
                    update public.books
                    set stock = stock + item_quantity, updated_at = now()
                    where book_id = (item ->> 'book_id')::uuid;
                end if;
            end loop;
        end if;

    elsif target_entry.entry_type = 'purchase' or target_entry.entry_type = 'restock' then
        if jsonb_typeof(target_entry.items) = 'array' then
            for item in select value from jsonb_array_elements(target_entry.items)
            loop
                item_quantity := greatest((item ->> 'quantity')::integer, 0);
                if item_quantity > 0 then
                    select * into target_book
                    from public.books
                    where book_id = (item ->> 'book_id')::uuid
                    for update;
                    if found and target_book.stock >= item_quantity then
                        update public.books
                        set stock = stock - item_quantity, updated_at = now()
                        where book_id = target_book.book_id;
                    else
                        raise exception 'Penghapusan pembelian tidak dapat dilakukan karena stok sudah berubah atau tidak mencukupi.' using errcode = 'P0001';
                    end if;
                end if;
            end loop;
        end if;

    elsif target_entry.entry_type in ('damaged', 'lost') then
        if jsonb_typeof(target_entry.items) = 'array' then
            for item in select value from jsonb_array_elements(target_entry.items)
            loop
                item_quantity := greatest((item ->> 'quantity')::integer, 0);
                if item_quantity > 0 then
                    update public.books
                    set stock = stock + item_quantity, updated_at = now()
                    where book_id = (item ->> 'book_id')::uuid;
                end if;
            end loop;
        end if;
    end if;

    delete from public.book_condition_events
    where journal_entry_id = target_entry.journal_entry_id;

    delete from public.journal_entries
    where journal_entry_id = target_entry.journal_entry_id;

    return jsonb_build_object(
        'deleted_journal_entry_id', p_journal_entry_id,
        'entry_type', target_entry.entry_type
    );
end;
$$;

create or replace function public.record_financial_activity(
    p_activity_type text,
    p_description text,
    p_amount numeric,
    p_entry_date timestamptz
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_entry public.journal_entries%rowtype;
begin
    if p_activity_type is null or p_activity_type not in ('sale', 'purchase', 'damaged', 'lost', 'income', 'expense') then
        raise exception 'Jenis aktivitas keuangan tidak valid.' using errcode = '22023';
    end if;
    if nullif(trim(p_description), '') is null then
        raise exception 'Keterangan aktivitas wajib diisi.' using errcode = '22023';
    end if;
    if p_amount is null or p_amount <= 0 then
        raise exception 'Nilai aktivitas harus lebih dari nol.' using errcode = '22023';
    end if;

    insert into public.journal_entries (
        entry_number, entry_type, description, debit_account, credit_account, amount, entry_date
    ) values (
        'JU-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS') || '-' || upper(substr(md5(random()::text), 1, 4)),
        p_activity_type,
        trim(p_description),
        case p_activity_type
            when 'sale' then 'Kas'
            when 'purchase' then 'Persediaan Buku'
            when 'damaged' then 'Kerugian Buku Rusak'
            when 'lost' then 'Kerugian Buku Hilang'
            when 'income' then 'Kas'
            else 'Beban Operasional'
        end,
        case p_activity_type
            when 'sale' then 'Pendapatan Penjualan'
            when 'purchase' then 'Utang Supplier'
            when 'damaged' then 'Persediaan Buku'
            when 'lost' then 'Persediaan Buku'
            when 'income' then 'Pendapatan Lain-lain'
            else 'Kas'
        end,
        p_amount,
        coalesce(p_entry_date, now())
    ) returning * into new_entry;
    return to_jsonb(new_entry);
end;
$$;

