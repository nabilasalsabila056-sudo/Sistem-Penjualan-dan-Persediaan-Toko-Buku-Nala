-- Tepat empat tabel utama: customers, books, sales, supplier_orders.
-- Item penjualan dan pemesanan disimpan sebagai JSONB agar ERD tetap empat tabel.

-- Tabel books yang sudah ada tidak dihapus; kolom relasi baru tetap nullable.
create table if not exists public.books (
    book_id uuid primary key default gen_random_uuid(),
    isbn text unique,
    title text not null,
    author text not null,
    publisher text,
    category text,
    price numeric(12, 2) not null check (price >= 0),
    stock integer not null default 0 check (stock >= 0),
    min_stock integer not null default 5 check (min_stock >= 0),
    warehouse_location text,
    image_url text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.books add column if not exists warehouse_location text;

create table if not exists public.customers (
    customer_id uuid primary key default gen_random_uuid(),
    name text not null,
    phone text,
    created_at timestamptz not null default now()
);

create table if not exists public.sales (
    sale_id bigint generated by default as identity primary key,
    receipt_number text not null unique,
    customer_id uuid references public.customers(customer_id) on delete set null,
    payment_method text not null default 'Tunai'
        check (payment_method in ('Tunai', 'Debit', 'Transfer', 'QRIS')),
    total numeric(12, 2) not null default 0 check (total >= 0),
    amount_received numeric(12, 2),
    items jsonb not null default '[]'::jsonb,
    sold_at timestamptz not null default now()
);

alter table public.sales drop constraint if exists sales_payment_method_check;
alter table public.sales add constraint sales_payment_method_check
    check (payment_method in ('Tunai', 'Debit', 'Transfer', 'QRIS'));

alter table public.sales add column if not exists items jsonb not null default '[]'::jsonb;
alter table public.sales add column if not exists amount_received numeric(12, 2);

create table if not exists public.supplier_orders (
    supplier_order_id bigint generated by default as identity primary key,
    order_number text not null unique,
    supplier_name text not null,
    supplier_contact text,
    warehouse_location text not null default 'Gudang Utama',
    notes text,
    total_cost numeric(12, 2) not null default 0 check (total_cost >= 0),
    items jsonb not null default '[]'::jsonb,
    status text not null default 'received' check (status in ('received', 'cancelled')),
    ordered_at timestamptz not null default now(),
    received_at timestamptz not null default now()
);

alter table public.supplier_orders add column if not exists items jsonb not null default '[]'::jsonb;

