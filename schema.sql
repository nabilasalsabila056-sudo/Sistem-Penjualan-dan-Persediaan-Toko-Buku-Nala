-- Sinkronkan entri jurnal rusak/hilang lama ke riwayat kondisi fisik.
do $$
declare
    j_entry public.journal_entries%rowtype;
    item jsonb;
begin
    for j_entry in
        select * from public.journal_entries
        where entry_type in ('damaged', 'lost')
    loop
        for item in select value from jsonb_array_elements(coalesce(j_entry.items, '[]'::jsonb))
        loop
            if nullif(item ->> 'book_id', '') is not null then
                insert into public.book_condition_events (
                    book_id, condition_type, quantity, notes, journal_entry_id, occurred_at
                )
                select
                    (item ->> 'book_id')::uuid,
                    j_entry.entry_type,
                    greatest((item ->> 'quantity')::integer, 1),
                    case
                        when j_entry.description like '%: %' then trim(split_part(j_entry.description, ': ', 2))
                        else null
                    end,
                    j_entry.journal_entry_id,
                    j_entry.entry_date
                where not exists (
                    select 1 from public.book_condition_events
                    where journal_entry_id = j_entry.journal_entry_id
                      and book_id = (item ->> 'book_id')::uuid
                      and condition_type = j_entry.entry_type
                );
            end if;
        end loop;
    end loop;

    update public.book_condition_events as event
    set notes = case
            when je.description like '%: %' then trim(split_part(je.description, ': ', 2))
            else null
        end
    from public.journal_entries as je
    where event.journal_entry_id = je.journal_entry_id
      and je.entry_type in ('damaged', 'lost');
end;
$$;

