-- Simpan transaksi, detail buku, dan pengurangan stok dalam satu transaksi PostgreSQL.
drop function if exists public.record_sale(text, text, text, jsonb);
drop function if exists public.record_sale(uuid, text, text, text, jsonb);
create or replace function public.record_sale(
    p_customer_id uuid,
    p_customer_name text,
    p_customer_phone text,
    p_payment_method text,
    p_amount_received numeric,
    p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_sale public.sales%rowtype;
    new_customer_id uuid;
    item jsonb;
    selected_book public.books%rowtype;
    item_quantity integer;
    sale_total numeric(12, 2) := 0;
    sale_items_json jsonb := '[]'::jsonb;
begin
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'Transaksi harus memiliki minimal satu buku.' using errcode = '22023';
    end if;

    new_customer_id := p_customer_id;

    if new_customer_id is null and nullif(trim(p_customer_name), '') is not null then
        insert into public.customers (name, phone)
        values (trim(p_customer_name), nullif(trim(p_customer_phone), ''))
        returning customer_id into new_customer_id;
    end if;

    insert into public.sales (receipt_number, customer_id, payment_method, total)
    values (
        'NLA-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS') || '-' || upper(substr(md5(random()::text), 1, 4)),
        new_customer_id,
        p_payment_method,
        0
    ) returning * into new_sale;

    for item in select value from jsonb_array_elements(p_items)
    loop
        item_quantity := (item ->> 'quantity')::integer;
        if item_quantity <= 0 then
            raise exception 'Jumlah buku harus lebih dari nol.' using errcode = '22023';
        end if;

        select * into selected_book
        from public.books
        where book_id = (item ->> 'book_id')::uuid
        for update;

        if not found then
            raise exception 'Buku tidak ditemukan.' using errcode = 'P0002';
        end if;
        if selected_book.stock < item_quantity then
            raise exception 'Stok % tidak mencukupi. Tersedia: %.', selected_book.title, selected_book.stock
                using errcode = 'P0001';
        end if;

        update public.books
        set stock = stock - item_quantity, updated_at = now()
        where book_id = selected_book.book_id;

        sale_items_json := sale_items_json || jsonb_build_array(jsonb_build_object(
            'book_id', selected_book.book_id,
            'title', selected_book.title,
            'quantity', item_quantity,
            'unit_price', selected_book.price
        ));
        sale_total := sale_total + selected_book.price * item_quantity;
    end loop;

    if p_amount_received is null or p_amount_received < sale_total then
        raise exception 'Jumlah uang yang diterima tidak boleh kurang dari total pembayaran.' using errcode = '22023';
    end if;

    update public.sales set total = sale_total, amount_received = p_amount_received, items = sale_items_json
    where sale_id = new_sale.sale_id
    returning * into new_sale;

    return to_jsonb(new_sale);
end;
$$;

-- Penerimaan supplier dan penambahan stok disimpan sebagai satu transaksi.
create or replace function public.record_supplier_order(
    p_supplier_name text,
    p_supplier_contact text,
    p_warehouse_location text,
    p_notes text,
    p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_order public.supplier_orders%rowtype;
    item jsonb;
    selected_book public.books%rowtype;
    item_quantity integer;
    item_cost numeric(12, 2);
    order_total numeric(12, 2) := 0;
    order_items_json jsonb := '[]'::jsonb;
begin
    if nullif(trim(p_supplier_name), '') is null then
        raise exception 'Nama supplier wajib diisi.' using errcode = '22023';
    end if;
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'Pemesanan harus berisi minimal satu buku.' using errcode = '22023';
    end if;

    insert into public.supplier_orders (
        order_number, supplier_name, supplier_contact, warehouse_location, notes
    ) values (
        'PO-' || to_char(clock_timestamp(), 'YYMMDDHH24MISSMS') || '-' || upper(substr(md5(random()::text), 1, 4)),
        trim(p_supplier_name), nullif(trim(p_supplier_contact), ''),
        coalesce(nullif(trim(p_warehouse_location), ''), 'Gudang Utama'), nullif(trim(p_notes), '')
    ) returning * into new_order;

    for item in select value from jsonb_array_elements(p_items)
    loop
        item_quantity := (item ->> 'quantity')::integer;
        item_cost := coalesce((item ->> 'unit_cost')::numeric, 0);
        if item_quantity <= 0 or item_cost < 0 then
            raise exception 'Jumlah dan harga modal pemesanan tidak valid.' using errcode = '22023';
        end if;

        select * into selected_book from public.books
        where book_id = (item ->> 'book_id')::uuid for update;
        if not found then
            raise exception 'Buku pada pemesanan tidak ditemukan.' using errcode = 'P0002';
        end if;

        update public.books
        set stock = stock + item_quantity,
            warehouse_location = new_order.warehouse_location,
            updated_at = now()
        where book_id = selected_book.book_id;

        order_items_json := order_items_json || jsonb_build_array(jsonb_build_object(
            'book_id', selected_book.book_id,
            'title', selected_book.title,
            'quantity', item_quantity,
            'unit_cost', item_cost
        ));
        order_total := order_total + item_quantity * item_cost;
    end loop;

    update public.supplier_orders set total_cost = order_total, items = order_items_json
    where supplier_order_id = new_order.supplier_order_id
    returning * into new_order;
    return to_jsonb(new_order);
end;
$$;

