-- Simpan nama dari relasi legacy ke atribut teks sebelum master lamanya dihapus.
do $$
declare
    suppliers_table regclass := to_regclass('public.suppliers');
    warehouses_table regclass := to_regclass('public.warehouses');
begin
    if suppliers_table is not null
       and exists (select 1 from pg_attribute where attrelid = 'public.books'::regclass and attname = 'supplier_id' and not attisdropped)
       and exists (select 1 from pg_attribute where attrelid = suppliers_table and attname = 'supplier_id' and not attisdropped)
    then
        execute $sql$
            update public.books as book
            set publisher = supplier.name
            from public.suppliers as supplier
            where book.supplier_id = supplier.supplier_id
              and nullif(trim(book.publisher), '') is null
        $sql$;
    end if;

     if warehouses_table is not null
         and exists (select 1 from pg_attribute where attrelid = 'public.books'::regclass and attname = 'warehouse_id' and not attisdropped)
         and exists (select 1 from pg_attribute where attrelid = warehouses_table and attname = 'warehouse_id' and not attisdropped)
    then
        execute $sql$
            update public.books as book
            set warehouse_location = warehouse.name
            from public.warehouses as warehouse
            where book.warehouse_id = warehouse.warehouse_id
              and nullif(trim(book.warehouse_location), '') is null
        $sql$;
    end if;
end;
$$;

